        "class SliceAttentionPool(nn.Module):\n",
        "    def __init__(self, embed_dim: int = 512):\n",
        "        super().__init__()\n",
        "        self.attn = nn.Sequential(\n",
        "            nn.Linear(embed_dim, 128),\n            nn.Tanh(),\n",
        "            nn.Linear(128, 1)\n",
        "        )\n",
        "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
        "        weights = F.softmax(self.attn(x), dim=1)\n",
        "        return torch.sum(x * weights, dim=1)\n",
        "\n",
        "class MILKneeNet(nn.Module):\n",
        "    def __init__(self, num_targets: int = 12):\n",
        "        super().__init__()\n",
        "        self.num_targets = num_targets\n",
        "        base_model = torchvision.models.resnet18(weights=None)\n",
        "        self.feature_dim = 512\n",
        "        self.backbone = nn.Sequential(*list(base_model.children())[:-1])\n",
        "        \n",
        "        self.sag_pool = SliceAttentionPool(self.feature_dim)\n",
        "        self.cor_pool = SliceAttentionPool(self.feature_dim)\n",
        "        self.ax_pool = SliceAttentionPool(self.feature_dim)\n",
        "        \n",
        "        self.classifier = nn.Sequential(\n",
        "            nn.Linear(self.feature_dim * 3, 256),\n",
        "            nn.GELU(),\n",
        "            nn.Dropout(0.3),\n",
        "            nn.Linear(256, num_targets)\n",
        "        )\n",
        "        \n",
        "    def extract_features(self, x: torch.Tensor) -> torch.Tensor:\n",
        "        B, S, C, H, W = x.shape\n",
        "        feats = self.backbone(x.view(B * S, C, H, W))\n",
        "        return feats.view(B, S, -1)\n",
        "        \n",
        "    def forward(self, sag: torch.Tensor, cor: torch.Tensor, ax: torch.Tensor) -> torch.Tensor:\n",
        "        sag_p = self.sag_pool(self.extract_features(sag))\n",
        "        cor_p = self.cor_pool(self.extract_features(cor))\n",
        "        ax_p = self.ax_pool(self.extract_features(ax))\n",
        "        return self.classifier(torch.cat([sag_p, cor_p, ax_p], dim=-1))\n",
        "\n",
