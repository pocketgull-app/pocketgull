            "class SliceAttentionPool(nn.Module):\n",
            "    def __init__(self, embed_dim: int = 512):\n",
            "        super().__init__()\n",
            "        self.attn = nn.Sequential(\n",
            "            nn.Linear(embed_dim, 128),\n            nn.Tanh(),\n",
            "            nn.Linear(128, 1)\n",
            "        )\n",
            "        \n",
            "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
            "        # x shape: (B, Slices, EmbedDim)\n",
            "        weights = self.attn(x)  # (B, Slices, 1)\n",
            "        weights = F.softmax(weights, dim=1)\n",
            "        pooled = torch.sum(x * weights, dim=1)\n",
            "        return pooled\n",
            "\n",
            "class MILKneeNet(nn.Module):\n",
            "    def __init__(self, num_targets: int = 12, backbone_name: str = 'resnet18'):\n",
            "        super().__init__()\n",
            "        self.num_targets = num_targets\n",
            "        \n",
            "        # Vision backbone (pretrained ResNet18/34)\n",
            "        if backbone_name == 'resnet18':\n",
            "            base_model = torchvision.models.resnet18(pretrained=True)\n",
            "            self.feature_dim = 512\n",
            "        else:\n",
            "            base_model = torchvision.models.resnet34(pretrained=True)\n",
            "            self.feature_dim = 512\n",
            "            \n",
            "        # Remove FC layers\n",
            "        self.backbone = nn.Sequential(*list(base_model.children())[:-1])\n",
            "        \n",
            "        # Slice attention poolers for each plane\n",
            "        self.sag_pool = SliceAttentionPool(self.feature_dim)\n",
            "        self.cor_pool = SliceAttentionPool(self.feature_dim)\n",
            "        self.ax_pool = SliceAttentionPool(self.feature_dim)\n",
            "        \n",
            "        # Vision aggregation head\n",
            "        self.classifier = nn.Sequential(\n",
            "            nn.Linear(self.feature_dim * 3, 256),\n",
            "            nn.GELU(),\n",
            "            nn.Dropout(0.3),\n",
            "            nn.Linear(256, num_targets)\n",
            "        )\n",
            "        \n",
            "    def extract_features(self, x: torch.Tensor) -> torch.Tensor:\n",
            "        # x shape: (B, Slices, 3, H, W)\n",
            "        B, S, C, H, W = x.shape\n",
            "        x_flat = x.view(B * S, C, H, W)\n",
            "        feats = self.backbone(x_flat)  # (B * S, EmbedDim, 1, 1)\n",
            "        feats = feats.view(B, S, -1)   # (B, S, EmbedDim)\n",
            "        return feats\n",
            "        \n",
            "    def forward(self, sag: torch.Tensor, cor: torch.Tensor, ax: torch.Tensor) -> torch.Tensor:\n",
            "        sag_feats = self.extract_features(sag)\n",
            "        cor_feats = self.extract_features(cor)\n",
            "        ax_feats = self.extract_features(ax)\n",
            "        \n",
            "        sag_pooled = self.sag_pool(sag_feats)\n",
            "        cor_pooled = self.cor_pool(cor_feats)\n",
            "        ax_pooled = self.ax_pool(ax_feats)\n",
            "        \n",
            "        merged = torch.cat([sag_pooled, cor_pooled, ax_pooled], dim=-1)\n",
            "        logits = self.classifier(merged)\n",
            "        return logits\n",
            "\n",
            "model_smoke = MILKneeNet(backbone_name=BACKBONE)\n",
            "print('[OK] MILKneeNet model loaded.')\n"
