            "def calculate_macro_auc(y_true: np.ndarray, y_pred: np.ndarray) -> float:\n",
            "    aucs = []\n",
            "    for i in range(y_true.shape[1]):\n",
            "        if len(np.unique(y_true[:, i])) > 1:\n",
            "            aucs.append(roc_auc_score(y_true[:, i], y_pred[:, i]))\n",
            "        else:\n",
            "            aucs.append(0.5)\n",
            "    return float(np.mean(aucs))\n",
            "\n",
            "def train_epoch(model, loader, optimizer, criterion, device, stage='weak'):\n",
            "    model.train()\n",
            "    total_loss = 0.0\n",
            "    for batch in loader:\n",
            "        sag = batch['sag'].to(device)\n",
            "        cor = batch['cor'].to(device)\n",
            "        ax = batch['ax'].to(device)\n",
            "        labels = batch['labels'].to(device)\n",
            "        conf = batch['confidences'].to(device)\n",
            "        \n",
            "        optimizer.zero_grad()\n",
            "        logits = model(sag, cor, ax)\n",
            "        \n",
            "        # Weighted BCE Loss based on label confidence\n",
            "        loss_raw = F.binary_cross_entropy_with_logits(logits, labels, reduction='none')\n",
            "        if stage == 'weak':\n",
            "            # Weight the loss by extraction confidence\n",
            "            loss = torch.mean(loss_raw * conf)\n",
            "        else:\n",
            "            loss = torch.mean(loss_raw)\n",
            "            \n",
            "        loss.backward()\n",
            "        optimizer.step()\n",
            "        total_loss += loss.item() * sag.size(0)\n",
            "        \n",
            "    return total_loss / len(loader.dataset)\n",
            "\n",
            "def evaluate_oof(model, loader, device):\n",
            "    model.eval()\n",
            "    all_preds = []\n",
            "    all_targets = []\n",
            "    with torch.no_grad():\n",
            "        for batch in loader:\n",
            "            sag = batch['sag'].to(device)\n",
            "            cor = batch['cor'].to(device)\n",
            "            ax = batch['ax'].to(device)\n",
            "            labels = batch['labels']\n",
            "            \n",
            "            logits = model(sag, cor, ax)\n",
            "            preds = torch.sigmoid(logits).cpu().numpy()\n",
            "            all_preds.append(preds)\n",
