            "    def apply_window(self, pixel_array: np.ndarray, center: float, width: float) -> np.ndarray:\n",
            "        min_val = center - width / 2.0\n",
            "        max_val = center + width / 2.0\n",
            "        windowed = np.clip(pixel_array, min_val, max_val)\n",
            "        return (windowed - min_val) / (max_val - min_val + 1e-6)\n",
            "        \n",
            "    def convert_to_3channel_rgb(self, slice_data: np.ndarray) -> np.ndarray:\n",
            "        # Channel 0: Soft Tissue\n",
            "        ch0 = self.apply_window(slice_data, center=400, width=1000)\n",
            "        # Channel 1: Fluid-Sensitive Edema\n",
            "        ch1 = self.apply_window(slice_data, center=700, width=2000)\n",
            "        # Channel 2: Sobel Edge Gradient\n",
            "        grad_y, grad_x = np.gradient(ch0)\n",
            "        ch2 = np.sqrt(grad_x**2 + grad_y**2)\n",
            "        ch2 = np.clip(ch2 / (np.max(ch2) + 1e-6), 0, 1)\n",
            "        return np.stack([ch0, ch1, ch2], axis=0).astype(np.float32)  # (3, H, W)\n",
