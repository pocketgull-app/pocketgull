            "        0.30 * norm_mean + 0.30 * norm_range + 0.40 * norm_std,\n",
            "        # PF OA: anterior trochlear signal\n",
            "        0.30 * norm_mean + 0.40 * norm_bright + 0.30 * norm_edge,\n",
            "        # Effusion: large bright fluid -> high bright fraction + high max\n",
            "        0.50 * norm_bright + 0.30 * norm_max + 0.20 * norm_std,\n",
            "        # Synovitis: peripheral thickening -> edge density + bright fraction\n",
            "        0.40 * norm_edge + 0.35 * norm_bright + 0.25 * norm_isv,\n",
            "        # Baker's Cyst: posterior bright focus -> bright fraction + intensity range\n",
            "        0.40 * norm_bright + 0.30 * norm_range + 0.30 * norm_max,\n",
            "        # Contusion: focal marrow edema -> inter-slice variance + bright patches\n",
            "        0.40 * norm_isv + 0.30 * norm_bright + 0.30 * norm_edge,\n",
            "        # Fracture: sharp linear discontinuity -> edge density + max intensity\n",
            "        0.50 * norm_edge + 0.30 * norm_max + 0.20 * norm_range,\n",
            "    ], dtype=np.float32)\n",
            "    \n",
            "    # Calibrate: blend raw features with population priors\n",
            "    calibrated = 0.40 * POPULATION_PRIORS + 0.60 * raw_features\n",
            "    return np.clip(calibrated, 0.01, 0.99)\n",
