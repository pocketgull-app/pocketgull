            "        bright_frac = float(np.mean(flat > p75))\n",
            "        bright_fractions.append(bright_frac)\n",
            "        \n",
            "        # Edge density: gradient magnitude (correlates with structural disruptions)\n",
            "        if arr.ndim == 2 and HAS_SCIPY:\n",
            "            gy, gx = np.gradient(arr)\n",
            "            grad_mag = np.sqrt(gx**2 + gy**2)\n",
            "            edge_densities.append(float(np.mean(grad_mag)) / (sigma + 1e-6))\n",
            "        else:\n",
            "            edge_densities.append(0.5)\n",
            "        \n",
            "        # Aspect ratio of the image\n",
            "        if arr.ndim >= 2:\n",
