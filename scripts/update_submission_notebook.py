            "        indices = np.linspace(0, n_files - 1, 16, dtype=int)\n",
            "        sample_files = [dcm_files[i] for i in indices]\n",
            "    else:\n",
            "        sample_files = dcm_files\n",
            "    \n",
            "    pixel_arrays = []\n",
            "    for fp in sample_files:\n",
