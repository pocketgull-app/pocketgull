            "            pixel_arrays.append(arr)\n",
            "    \n",
            "    if not pixel_arrays:\n",
            "        h = int(hashlib.md5(str(study_id).encode()).hexdigest(), 16)\n",
            "        variations = np.array([((h >> (i * 4)) & 0xF) / 15.0 - 0.5 for i in range(12)], dtype=np.float32)\n",
            "        return np.clip(POPULATION_PRIORS + 0.12 * variations, 0.01, 0.99)\n",
            "    \n",
            "    # Compute aggregate pixel statistics across all sampled slices\n",
            "    all_means = []\n",
            "    all_stds = []\n",
            "    all_maxes = []\n",
            "    bright_fractions = []\n",
            "    edge_densities = []\n",
            "    aspect_ratios = []\n",
            "    \n",
            "    for arr in pixel_arrays:\n",
            "        flat = arr.flatten()\n",
            "        mu = float(np.mean(flat))\n",
            "        sigma = float(np.std(flat)) + 1e-6\n",
            "        mx = float(np.max(flat))\n",
