            "\n",
            "def discover_dicom_files(study_dir: str) -> list:\n",
            "    \"\"\"Extension-agnostic file search via os.walk().\"\"\"\n",
            "    if not os.path.exists(study_dir):\n",
            "        return []\n",
            "    all_files = []\n",
            "    for root, dirs, files in os.walk(study_dir):\n",
            "        for f in files:\n",
            "            if not f.startswith('.'):\n",
            "                all_files.append(os.path.join(root, f))\n",
            "    return sorted(all_files)\n",
            "\n",
            "def read_pixel_array(filepath: str) -> Optional[np.ndarray]:\n",
            "    \"\"\"Safely read a DICOM pixel array.\"\"\"\n",
            "    if not HAS_PYDICOM:\n",
            "        return None\n",
            "    try:\n",
            "        ds = pydicom.dcmread(filepath, force=True)\n",
            "        if not hasattr(ds, 'pixel_array'):\n",
            "            ds.file_meta.TransferSyntaxUID = pydicom.uid.ImplicitVRLittleEndian\n",
            "        arr = ds.pixel_array.astype(np.float32)\n",
            "        return arr\n",
            "    except Exception:\n",
            "        return None\n",
            "\n",
            "def extract_biophysical_features(study_id: str) -> np.ndarray:\n",
            "    \"\"\"Extract 12 radiological pixel features from a study's DICOM slices.\n",
            "    \n",
            "    Each feature is designed to correlate with one of the 12 target abnormalities:\n",
            "      0  ACL: High-signal focus in intercondylar notch (sagittal bright streak)\n",
            "      1  MCL: Medial-side high-signal band (coronal bright edge)\n",
            "      2  Medial Meniscus: Surface-touching signal in medial compartment\n",
            "      3  Lateral Meniscus: Surface-touching signal in lateral compartment\n",
            "      4  Medial OA: Subchondral signal change in medial tibial plateau\n",
            "      5  Lateral OA: Subchondral signal change in lateral tibial plateau\n",
            "      6  PF OA: Anterior trochlear signal (axial/sagittal anterior bright)\n",
            "      7  Effusion: Large bright fluid region (high-signal volume fraction)\n",
            "      8  Synovitis: Peripheral bright thickening near joint capsule\n",
            "      9  Baker's Cyst: Posterior bright focus (popliteal region)\n",
            "     10  Contusion: Focal bone marrow edema patch (mid-intensity spread)\n",
            "     11  Fracture: Sharp high-contrast linear discontinuity\n",
            "    \"\"\"\n",
