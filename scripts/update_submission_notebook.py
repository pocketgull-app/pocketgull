            "    \n",
            "    # Normalize features to [0, 1] range approximately\n",
            "    norm_mean = np.clip(mean_intensity / 2000.0, 0, 1)\n",
            "    norm_std = np.clip(std_intensity / 1000.0, 0, 1)\n",
            "    norm_max = np.clip(max_intensity / 4096.0, 0, 1)\n",
            "    norm_bright = np.clip(mean_bright_frac, 0, 1)\n",
            "    norm_edge = np.clip(mean_edge_density, 0, 1)\n",
            "    norm_range = np.clip(intensity_range / 4096.0, 0, 1)\n",
            "    norm_isv = np.clip(inter_slice_var, 0, 1)\n",
            "    \n",
            "    # Map features to 12 target probabilities\n",
            "    # Each target gets a weighted combination of features biased toward its clinical correlate\n",
            "    raw_features = np.array([\n",
