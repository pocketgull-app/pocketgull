        "class AsymmetricLoss(nn.Module):\n",
        "    \"\"\"Asymmetric Loss (ASL) for multi-label classification with severe class imbalance.\"\"\"\n",
        "    def __init__(self, gamma_neg: float = 4.0, gamma_pos: float = 1.0, clip: float = 0.05, eps: float = 1e-8):\n",
        "        super().__init__()\n",
        "        self.gamma_neg = gamma_neg\n",
        "        self.gamma_pos = gamma_pos\n",
        "        self.clip = clip\n",
        "        self.eps = eps\n",
        "        \n",
        "    def forward(self, logits: torch.Tensor, targets: torch.Tensor, weights: Optional[torch.Tensor] = None) -> torch.Tensor:\n",
        "        probs = torch.sigmoid(logits)\n",
        "        probs_pos = probs\n",
        "        probs_neg = 1.0 - probs\n",
        "        \n",
        "        if self.clip > 0:\n",
        "            probs_neg = (probs_neg + self.clip).clamp(max=1.0)\n",
        "            \n",
        "        loss_pos = targets * torch.log(probs_pos.clamp(min=self.eps)) * ((1.0 - probs_pos) ** self.gamma_pos)\n",
        "        loss_neg = (1.0 - targets) * torch.log(probs_neg.clamp(min=self.eps)) * (probs_pos ** self.gamma_neg)\n",
        "        loss = -(loss_pos + loss_neg)\n",
        "        \n",
        "        if weights is not None:\n",
        "            loss = loss * weights.unsqueeze(-1)\n",
        "            \n",
        "        return loss.mean()\n",
        "\n",
        "class SliceAttentionPool(nn.Module):\n",
        "    def __init__(self, embed_dim: int = 512):\n",
        "        super().__init__()\n",
        "        self.attn = nn.Sequential(\n",
        "            nn.Linear(embed_dim, 128),\n            nn.Tanh(),\n",
        "            nn.Linear(128, 1)\n",
        "        )\n",
        "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
        "        weights = F.softmax(self.attn(x), dim=1)\n",
        "        return torch.sum(x * weights, dim=1)\n",
        "\n",
        "class MILKneeNet(nn.Module):\n",
        "    def __init__(self, num_targets: int = 12, backbone_name: str = 'resnet18'):\n",
        "        super().__init__()\n",
        "        self.num_targets = num_targets\n",
        "        base_model = torchvision.models.resnet18(weights=torchvision.models.ResNet18_Weights.DEFAULT if hasattr(torchvision.models, 'ResNet18_Weights') else None)\n",
        "        self.feature_dim = 512\n",
        "        self.backbone = nn.Sequential(*list(base_model.children())[:-1])\n",
        "        \n",
        "        self.sag_pool = SliceAttentionPool(self.feature_dim)\n",
        "        self.cor_pool = SliceAttentionPool(self.feature_dim)\n",
        "        self.ax_pool = SliceAttentionPool(self.feature_dim)\n",
        "        \n",
        "        self.classifier = nn.Sequential(\n",
        "            nn.Linear(self.feature_dim * 3, 256),\n",
        "            nn.GELU(),\n",
        "            nn.Dropout(0.3),\n",
        "            nn.Linear(256, num_targets)\n",
        "        )\n",
        "        \n",
        "    def extract_features(self, x: torch.Tensor) -> torch.Tensor:\n",
        "        B, S, C, H, W = x.shape\n",
        "        feats = self.backbone(x.view(B * S, C, H, W))\n",
        "        return feats.view(B, S, -1)\n",
        "        \n",
        "    def forward(self, sag: torch.Tensor, cor: torch.Tensor, ax: torch.Tensor) -> torch.Tensor:\n",
        "        sag_p = self.sag_pool(self.extract_features(sag))\n",
        "        cor_p = self.cor_pool(self.extract_features(cor))\n",
        "        ax_p = self.ax_pool(self.extract_features(ax))\n",
        "        return self.classifier(torch.cat([sag_p, cor_p, ax_p], dim=-1))\n",
        "\n",
