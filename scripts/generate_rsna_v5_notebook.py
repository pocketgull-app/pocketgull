        "class RSNAKneeDataset(Dataset):\n",
        "    def __init__(self, df: pd.DataFrame, series_df: pd.DataFrame, img_dir: str, is_train: bool = True):\n",
        "        self.df = df.reset_index(drop=True)\n",
        "        self.series_df = series_df\n",
        "        self.img_dir = img_dir\n",
        "        self.is_train = is_train\n",
        "        \n",
        "    def __len__(self):\n",
        "        return len(self.df)\n",
        "        \n",
        "    def apply_window(self, pixel_array: np.ndarray, center: float, width: float) -> np.ndarray:\n",
        "        min_val = center - width / 2.0\n",
        "        max_val = center + width / 2.0\n",
        "        windowed = np.clip(pixel_array, min_val, max_val)\n",
        "        return (windowed - min_val) / (max_val - min_val + 1e-6)\n",
        "        \n",
        "    def convert_to_3channel_rgb(self, slice_data: np.ndarray) -> np.ndarray:\n",
        "        ch0 = self.apply_window(slice_data, center=400, width=1000)\n",
        "        ch1 = self.apply_window(slice_data, center=700, width=2000)\n",
        "        grad_y, grad_x = np.gradient(ch0)\n",
        "        ch2 = np.sqrt(grad_x**2 + grad_y**2)\n",
        "        ch2 = np.clip(ch2 / (np.max(ch2) + 1e-6), 0, 1)\n",
        "        return np.stack([ch0, ch1, ch2], axis=0).astype(np.float32)\n",
        "        \n",
        "    def read_study_plane_slices(self, study_uid: str, plane: str) -> torch.Tensor:\n",
        "        matched = self.series_df[(self.series_df['StudyInstanceUID'] == study_uid) & \n",
        "                                 (self.series_df['Anatomical_Plane'] == plane)]\n",
        "        \n",
        "        tensor_out = torch.zeros((NUM_SLICES_PER_PLANE, 3, IMAGE_SIZE, IMAGE_SIZE), dtype=torch.float32)\n",
        "        if matched.empty:\n",
        "            return tensor_out\n",
        "            \n",
        "        series_uid = matched.iloc[0]['SeriesInstanceUID']\n",
        "        series_dir = os.path.join(self.img_dir, study_uid, series_uid)\n",
        "        if not os.path.exists(series_dir):\n",
        "            return tensor_out\n",
        "            \n",
        "        files = sorted([os.path.join(series_dir, f) for f in os.listdir(series_dir) if not f.startswith('.')])\n",
        "        if not files:\n",
        "            return tensor_out\n",
        "            \n",
        "        n_files = len(files)\n",
        "        if n_files > NUM_SLICES_PER_PLANE:\n",
        "            indices = np.linspace(0, n_files - 1, NUM_SLICES_PER_PLANE, dtype=int)\n",
