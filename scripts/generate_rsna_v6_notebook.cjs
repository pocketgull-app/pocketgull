      "def rank_average_predictions(preds_list: List[np.ndarray], weights: Optional[List[float]] = None) -> np.ndarray:\n",
      "    \"\"\"Rank-averages multiple model prediction matrices to directly optimize Macro AUC-ROC.\"\"\"\n",
      "    if weights is None:\n",
      "        weights = [1.0 / len(preds_list)] * len(preds_list)\n",
      "    \n",
      "    num_samples, num_classes = preds_list[0].shape\n",
      "    final_ranks = np.zeros((num_samples, num_classes), dtype=np.float64)\n",
      "\n",
      "    for model_idx, preds in enumerate(preds_list):\n",
      "        w = weights[model_idx]\n",
      "        for c in range(num_classes):\n",
      "            col_preds = preds[:, c]\n",
      "            ranked = pd.Series(col_preds).rank(pct=True).values\n",
      "            final_ranks[:, c] += w * ranked\n",
      "\n",
      "    return final_ranks\n",
      "\n",
      "print('[OK] Rank-average ensembling ready')\n"
