      "        u = self.attention_u(x)\n",
      "        gated = v * u\n",
      "        a = self.attention_weights(gated) # (B, N, 1)\n",
      "        alpha = F.softmax(a, dim=1)\n",
      "        pooled = torch.sum(x * alpha, dim=1) # (B, D)\n",
