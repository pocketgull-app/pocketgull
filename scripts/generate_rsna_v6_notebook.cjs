      "class AsymmetricLoss(nn.Module):\n",
      "    \"\"\"Asymmetric Loss (ASL) with probability margin clipping.\n",
      "    Focuses gradient backprop on hard positive abnormalities (gamma_pos=1.0) \n",
      "    while aggressively suppressing false-positive noise (gamma_neg=4.0).\n",
      "    \"\"\"\n",
      "    def __init__(self, gamma_neg=4.0, gamma_pos=1.0, clip=0.05, eps=1e-8):\n",
      "        super().__init__()\n",
      "        self.gamma_neg = gamma_neg\n",
      "        self.gamma_pos = gamma_pos\n",
      "        self.clip = clip\n",
      "        self.eps = eps\n",
      "\n",
      "    def forward(self, x, y, sample_weights=None):\n",
      "        # x: logits (B, K), y: targets (B, K)\n",
      "        p = torch.sigmoid(x)\n",
      "        p_pos = p\n",
      "        p_neg = 1.0 - p\n",
      "\n",
      "        # Asymmetric clipping\n",
      "        if self.clip > 0:\n",
      "            p_neg = (p_neg + self.clip).clamp(max=1.0)\n",
      "\n",
      "        # Basic cross-entropy terms\n",
      "        los_pos = y * torch.log(p_pos.clamp(min=self.eps))\n",
      "        los_neg = (1.0 - y) * torch.log(p_neg.clamp(min=self.eps))\n",
      "\n",
      "        # Asymmetric focusing\n",
      "        los_pos = los_pos * ((1.0 - p_pos) ** self.gamma_pos)\n",
      "        los_neg = los_neg * (p ** self.gamma_neg)\n",
      "\n",
      "        loss = - (los_pos + los_neg)\n",
      "\n",
      "        if sample_weights is not None:\n",
      "            loss = loss * sample_weights.unsqueeze(-1)\n",
      "\n",
      "        return loss.mean()\n",
      "\n",
      "print('[OK] AsymmetricLoss module compiled successfully')\n"
