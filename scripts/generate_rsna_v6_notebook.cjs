      "    \"\"\"Multi-Instance Gated Attention Pooling for 2.5D MRI Slices.\"\"\"\n",
      "    def __init__(self, in_features: int, hidden_dim: int = 128):\n",
      "        super().__init__()\n",
      "        self.attention_v = nn.Sequential(nn.Linear(in_features, hidden_dim), nn.Tanh())\n",
