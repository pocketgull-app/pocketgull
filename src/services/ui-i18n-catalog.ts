export function localizeClinicalReportMarkdown(code: string, markdown: string): string {
  const resolved = resolveCatalogLangCode(code);
  if (resolved === 'en' || !markdown) return markdown;
  let localized = markdown;
  for (const [pattern, translations] of [...HEADING_DICTIONARY, ...CLINICAL_PROSE_DICTIONARY]) {
    const replacement = translations[resolved];
    if (replacement) {
      localized = localized.replace(pattern, replacement);
    }
  }
  return localized;
}

export function mapCodeToCarePlanLanguage(code: string, nativeOrEnglishName?: string): {
  presetLanguage: string;
  customLanguage: string;
  isCustom: boolean;
} {
  const preset = CODE_TO_CARE_PLAN_LANG[code];
  if (preset) {
    return { presetLanguage: preset, customLanguage: '', isCustom: false };
  }
  const fallbackName = nativeOrEnglishName || code;
  return { presetLanguage: 'custom', customLanguage: fallbackName, isCustom: true };
}

export function mapCarePlanLanguageToCode(lang: string): string | null {
  return CARE_PLAN_LANG_TO_CODE[lang.trim().toLowerCase()] ?? null;
}
