export function resolveCatalogLangCode(code: string | null | undefined): string {
  const normalized = (code || 'en').trim().toLowerCase();
  if (!normalized) return 'en';
  if (UI_TRANSLATIONS[normalized] || extendedCatalogRuntime[normalized] || KNOWN_EXTENDED_LANG_CODES.has(normalized)) {
    return normalized;
  }
  if (normalized.startsWith('zh')) return 'zh';
  const base = normalized.split('-')[0];
  if (UI_TRANSLATIONS[base] || extendedCatalogRuntime[base] || KNOWN_EXTENDED_LANG_CODES.has(base)) {
    return base;
  }
  return 'en';
}

export function translateUiKey(code: string, key: string, englishFallback?: string): string {
  const resolved = resolveCatalogLangCode(code);
  const extended = extendedCatalogRuntime[resolved]?.[key];
  if (extended) return extended;
  const primary = UI_TRANSLATIONS[resolved]?.[key];
  if (primary) return primary;
  return extendedCatalogRuntime['en']?.[key] ?? UI_TRANSLATIONS['en']?.[key] ?? englishFallback ?? key;
}

