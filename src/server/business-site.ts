      // 4. Formal 3D Double-Click & Double-Tap Flip Card State Machine
      class FlipCardStateMachine {
        constructor(containerEl) {
          this.container = containerEl;
          this.inner = containerEl.querySelector('.flip-card-inner');
          this.state = 'FRONT'; // 'FRONT' | 'FLIPPING' | 'BACK'
          this.lastTapTime = 0;
          this.lastTouchPos = { x: 0, y: 0 };
          this.doubleTapThresholdMs = 350;
          this.jitterRadiusPx = 24;

          this.initAccessibility();
          this.bindEvents();
        }

        initAccessibility() {
          this.container.setAttribute('tabindex', '0');
          this.container.setAttribute('role', 'region');
          this.container.setAttribute('aria-expanded', 'false');
          this.container.setAttribute('data-flip-state', 'front');
        }

        toggle(source = 'interaction') {
          if (this.state === 'FLIPPING') return;

          const targetState = this.state === 'FRONT' ? 'BACK' : 'FRONT';
          this.state = 'FLIPPING';
          this.container.setAttribute('data-flip-state', 'flipping');

          if (targetState === 'BACK') {
            this.inner.classList.add('is-flipped');
            this.container.setAttribute('aria-expanded', 'true');
          } else {
            this.inner.classList.remove('is-flipped');
            this.container.setAttribute('aria-expanded', 'false');
          }

          // Subtle haptic response on supported mobile devices
          if (typeof navigator !== 'undefined' && navigator.vibrate) {
            try { navigator.vibrate(15); } catch (e) {}
          }

          // Complete state transition upon CSS animation end
          const onTransitionEnd = (e) => {
            if (e.target !== this.inner) return;
            this.inner.removeEventListener('transitionend', onTransitionEnd);
            this.state = targetState;
            this.container.setAttribute('data-flip-state', targetState.toLowerCase());
            
            // Dispatch event for analytics / parent hooks
            this.container.dispatchEvent(new CustomEvent('pocketgull:card-flip', {
              bubbles: true,
              detail: { state: this.state, source: source, cardId: this.container.getAttribute('data-flip-id') }
            }));
          };

          this.inner.addEventListener('transitionend', onTransitionEnd, { once: true });
        }

        bindEvents() {
          // A. Desktop Double-Click
          this.container.addEventListener('dblclick', (e) => {
            e.preventDefault();
            this.toggle('desktop-dblclick');
          });

          // B. Mobile Double-Tap State Engine (with Jitter Radius & Velocity Check)
          this.container.addEventListener('touchstart', (e) => {
            if (e.touches.length > 1) return;
            const touch = e.touches[0];
            const now = performance.now();
            const delta = now - this.lastTapTime;
            const dist = Math.hypot(touch.clientX - this.lastTouchPos.x, touch.clientY - this.lastTouchPos.y);

            if (delta > 40 && delta < this.doubleTapThresholdMs && dist < this.jitterRadiusPx) {
              e.preventDefault(); // Prevent zoom
              this.toggle('mobile-doubletap');
              this.lastTapTime = 0;
            } else {
              this.lastTapTime = now;
              this.lastTouchPos = { x: touch.clientX, y: touch.clientY };
            }
          }, { passive: false });

          // C. Keyboard Accessibility (Enter, Space to toggle, Escape to reset to Front)
          this.container.addEventListener('keydown', (e) => {
            if (e.key === 'Enter' || e.key === ' ') {
              e.preventDefault();
              this.toggle('keyboard');
            } else if (e.key === 'Escape' && this.state === 'BACK') {
              e.preventDefault();
              this.toggle('keyboard-escape');
            }
          });

          // D. Explicit 1-Click Trigger Button Support
          this.container.querySelectorAll('.flip-trigger-btn').forEach(btn => {
            btn.addEventListener('click', (e) => {
              e.stopPropagation();
              this.toggle('button-click');
            });
          });
        }
      }

